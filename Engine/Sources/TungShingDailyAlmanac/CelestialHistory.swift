/// An offline anniversary daybook. Historical dates follow the cited archive's
/// convention; GCAT launches use UTC Gregorian dates. See docs/celestial-history.md.
/// Launch data from GCAT (J. McDowell, planet4589.org/space/gcat), CC BY 4.0.
public enum CelestialHistory {
    public struct Entry: Sendable, Equatable {
        public let month: Int
        public let day: Int
        public let year: Int
        public let text: String
        public let sourceID: String
        public let sourceURL: URL
    }

    public static let attribution = "Historical launch data: J. McDowell / GCAT (CC BY 4.0)"
    public static let attributionURL = URL(string: "https://planet4589.org/space/gcat/")!

    /// Validated civil dates always have an anniversary, including February 29.
    public static func entry(on date: GregorianDate) -> Entry {
        indexed[Int(date.month) * 100 + Int(date.day)]!
    }

    /// A year-independent anniversary lookup; February 29 is valid.
    /// Invalid components, including integers outside civil bounds, return nil.
    public static func entry(month: Int, day: Int) -> Entry? {
        guard (1...12).contains(month), (1...31).contains(day) else { return nil }
        return indexed[month * 100 + day]
    }

    private static let indexed = Dictionary(uniqueKeysWithValues: allEntries.map {
        ($0.month * 100 + $0.day, $0)
    })

    private static func launch(_ month: Int, _ day: Int, _ year: Int, _ text: String, _ sourceID: String) -> Entry {
        Entry(month: month, day: day, year: year, text: text, sourceID: sourceID,
              sourceURL: URL(string: "https://planet4589.org/space/gcat/tsv/derived/launchlog.tsv")!)
    }

    private static func event(_ month: Int, _ day: Int, _ year: Int, _ text: String, _ sourceID: String, _ url: String) -> Entry {
        Entry(month: month, day: day, year: year, text: text, sourceID: sourceID, sourceURL: URL(string: url)!)
    }

