    static func rank(_ tokens: [String], date: String, side: Side) -> [String] {
        let candidates = tokens.filter { !hidden.contains($0) }
        let pictured = observed[date]?[side.rawValue] ?? []
        let first = pictured.filter(candidates.contains)
        let remaining = candidates.enumerated().filter { !first.contains($0.element) }
        return first + remaining.sorted {
            let left = scores[side.rawValue]?[$0.element] ?? 0
            let right = scores[side.rawValue]?[$1.element] ?? 0
            return left == right ? $0.offset < $1.offset : left > right
        }.map(\.element)
    }
